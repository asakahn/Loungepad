// What the add-ons repository's checks need to know about the launcher's actions, read out of
// Loungepad/Models/Actions.cs (docs/ACTION-SHARING.md, "Community layouts"):
//
//   named    the key names ShortcutKeys knows ("PageDown", "MediaNext", ...)
//   packs    every bundled pack: id, name, exes, and each tab's actions (name, keys, button)
//   vectors  tests/shortcut-keys-vectors.json: chords and what the launcher makes of them, which
//            the C# harness and loungepad-addons' check-actions.mjs both have to agree with
//
//   node tools\action-data.mjs > ..\loungepad-addons\tools\launcher-data.json
//
// Run it after changing a pack, the key names or the vectors, and commit the copy there. It is a
// copy on purpose: the checks run against a file the pull request can see, not against whatever
// the launcher's main branch says that day.
import fs from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const actionsFile = new URL("../Loungepad/Models/Actions.cs", import.meta.url);
const vectorsFile = new URL("../tests/shortcut-keys-vectors.json", import.meta.url);

/** The packs, as plain objects: [{ id, name, exes, tabs: [{ id, name, items: [{ id, name, keys, desc, button, danger }] }] }]. */
export function readPacks() {
  const src = fs.readFileSync(actionsFile, "utf8");
  // The packs are written in a C# that is a few rewrites from JavaScript.
  let body = src.slice(src.indexOf("private static ActionTab[] Browser"), src.indexOf("public static ActionApp? Find"));
  body = body
    .replace(/private static ActionTab\[\] Browser\(string downloads, string privateWindow\) => new\[\]\s*\{/, "const Browser = (downloads, privateWindow) => [")
    .replace(/\};\s*public static IReadOnlyList<ActionApp> All \{ get; \} = new List<ActionApp>\s*\{/, "];\nconst All = [")
    .replace(/\};\s*$/, "];")
    .replace(/Array\.Empty<string>\(\)/g, "[]")
    .replace(/new\[\] \{ ([^}]*) \}/g, "[$1]")
    .replace(/EverywhereId/g, '"everywhere"')
    .replace(/danger: true/g, "null, true");
  const A = (id, name, keys, desc, button = null, danger = false) => ({ id, name, keys, desc, button, danger });
  const T = (id, name, ...items) => ({ id, name, items });
  const App = (id, name, exes, ...tabs) => ({ id, name, exes, tabs: tabs.flat() });
  return new Function("A", "T", "App", body + "\nreturn All;")(A, T, App);
}

/** The names ShortcutKeys.Named knows, as the page spells them. */
export function readNamedKeys() {
  const src = fs.readFileSync(actionsFile, "utf8");
  const start = src.indexOf("Dictionary<string, (ushort Vk, bool Ext)> Named");
  const block = src.slice(start, src.indexOf("};", start));
  return [...block.matchAll(/\["([A-Za-z]+)"\]\s*=/g)].map(m => m[1]);
}

export function readVectors() {
  return JSON.parse(fs.readFileSync(vectorsFile, "utf8"));
}

if (process.argv[1] && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()) {
  const packs = readPacks().map(p => ({
    id: p.id, name: p.name, exes: p.exes,
    tabs: p.tabs.map(t => ({ name: t.name, actions: t.items.map(a => ({ name: a.name, keys: a.keys, ...(a.button ? { button: a.button } : {}) })) })),
  }));
  const data = {
    note: "Generated by tools/action-data.mjs in the Loungepad repository. Do not edit by hand.",
    named: readNamedKeys(),
    packs,
    vectors: readVectors(),
  };
  process.stdout.write(JSON.stringify(data, null, 2) + "\n");
}
